function w(
  word: string,
  translationRu: string,
  translationUz: string,
  pronunciation: string,
  example: string,
  partOfSpeech: string,
  difficulty?: SkillDifficulty
): VocabWordSeed {
  return {
    word,
    translationRu,
    translationUz,
    pronunciation,
    example,
    partOfSpeech,
    ...(difficulty ? { difficulty } : {}),
  };
}

function topic(
  title: string,
  description: string,
  difficulty: SkillDifficulty,
  words: VocabWordSeed[],
  slug?: string
): VocabTopicSeed {
  return {
    slug: slug ?? slugify(title),
    title,
    description,
    difficulty,
    words,
  };
}

export function buildVocabularyQuestions(topicSeed: VocabTopicSeed): SkillQuestion[] {
  return buildQuestionsFromWords(
    topicSeed.words,
    `vocab:${topicSeed.slug}:${topicSeed.words.length}`
  );
}

