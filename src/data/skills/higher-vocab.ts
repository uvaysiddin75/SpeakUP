import { slugify } from "./helpers";
import type { Cefr, SkillDifficulty, VocabTopicSeed, VocabWordSeed } from "./types";

type Row = [string, string, string, string, string, string];

function toWords(rows: Row[], difficulty: SkillDifficulty): VocabWordSeed[] {
  return rows.map(([word, translationRu, translationUz, pronunciation, example, partOfSpeech]) => ({
    word,
    translationRu,
    translationUz,
    pronunciation,
    example,
    partOfSpeech,
    difficulty,
  }));
}

function topic(
  title: string,
  description: string,
  difficulty: SkillDifficulty,
  rows: Row[],
): VocabTopicSeed {
  return {
    slug: slugify(title),
    title,
    description,
    difficulty,
    words: toWords(rows, difficulty),
  };
}

