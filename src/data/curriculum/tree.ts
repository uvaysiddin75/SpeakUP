import {
  defaultGrammarSubtopics,
  lightSubtopics,
  slugify,
  type SeedCategory,
  type SeedLevel,
  type SeedTopic,
} from "./types";

function grammarTopics(
  items: Array<{ title: string; description: string; full?: boolean }>,
): SeedTopic[] {
  return items.map((item, index) => ({
    slug: slugify(item.title),
    title: item.title,
    description: item.description,
    difficulty: "EASY" as const,
    subtopics:
      item.full === false
        ? lightSubtopics(item.title, 5)
        : defaultGrammarSubtopics(item.title).map((sub, i) => ({
            ...sub,
            // First topics get full content; later ones still have structure
            withContent: index < 12 || i < 4,
          })),
  }));
}

function vocabTopics(titles: string[], fullCount = 4): SeedTopic[] {
  return titles.map((title, index) => ({
    slug: slugify(title),
    title,
    description: `Essential ${title.toLowerCase()} vocabulary for this level.`,
    difficulty: "EASY" as const,
    subtopics: [
      {
        slug: "word-list",
        title: "Core word list",
        description: `Key ${title.toLowerCase()} words with translations.`,
        withContent: index < fullCount,
      },
      {
        slug: "examples",
        title: "Example sentences",
        description: `See ${title.toLowerCase()} words in context.`,
        withContent: index < fullCount,
      },
      {
        slug: "collocations",
        title: "Useful phrases",
        description: `Common phrases related to ${title.toLowerCase()}.`,
        withContent: index < fullCount,
      },
      {
        slug: "practice",
        title: "Vocabulary practice",
        description: `Check your ${title.toLowerCase()} vocabulary.`,
        withContent: index < fullCount,
      },
      {
        slug: "review",
        title: "Review",
        description: `Review ${title.toLowerCase()} before the topic test.`,
        withContent: index < Math.min(2, fullCount),
      },
    ],
  }));
}

function skillTopics(
  kind: "Reading" | "Listening" | "Writing" | "Speaking",
  titles: string[],
  fullCount = 3,
): SeedTopic[] {
  return titles.map((title, index) => ({
    slug: slugify(title),
    title,
    description: `${kind} practice: ${title}.`,
    difficulty: "EASY" as const,
    subtopics: [
      {
        slug: "prepare",
        title: "Prepare",
        description: `Get ready for this ${kind.toLowerCase()} task.`,
        withContent: index < fullCount,
      },
      {
        slug: "main-task",
        title: "Main task",
        description: `Complete the main ${kind.toLowerCase()} activity.`,
        withContent: index < fullCount,
      },
      {
        slug: "comprehension",
        title: "Check understanding",
        description: `Questions and reflection for ${title}.`,
        withContent: index < fullCount,
      },
      {
        slug: "review",
        title: "Review",
        description: `Review key language from ${title}.`,
        withContent: index < Math.min(2, fullCount),
      },
    ],
  }));
}

function categoriesFor(
  grammar: SeedTopic[],
  vocabulary: SeedTopic[],
  reading: SeedTopic[],
  listening: SeedTopic[],
  writing: SeedTopic[],
  speaking: SeedTopic[],
): SeedCategory[] {
  return [
    { type: "GRAMMAR", topics: grammar },
    { type: "VOCABULARY", topics: vocabulary },
    { type: "READING", topics: reading },
    { type: "LISTENING", topics: listening },
    { type: "WRITING", topics: writing },
    { type: "SPEAKING", topics: speaking },
  ];
}

